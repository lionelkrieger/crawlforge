#!/usr/bin/env python3
"""Traceability check between the capability register and the architecture.

Reads register/capabilities.yaml and every .md under architecture/ (excluding
baseline/ and changes/), finds '> Capabilities: ...' lines under headings, and:
  - fails on unknown capability IDs and malformed traceability lines;
  - fails on capabilities tagged nowhere unless listed in untagged.yaml
    (spec gaps with a draft CR, scope decisions pending, or out of scope);
  - writes architecture/TRACEABILITY.md (deterministic).
Exit code 0 = pass.
"""
import re, sys
from pathlib import Path
import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
ARCH = ROOT / "architecture"
TAG = re.compile(r"^> Capabilities: (.+)$")
CAP = re.compile(r"^CAP-(A|B|B2|C|D1|D2|E|F|G|H|I|J|K|L)-(\d{3}|X\d{2})$")
SECTIONS = ["A", "B", "B2", "C", "D1", "D2", "E", "F", "G", "H", "I", "J", "K", "L"]

def key(c):
    p = c.split("-")
    return (SECTIONS.index(p[1]), p[2])

caps = {c["id"]: c for c in yaml.safe_load((HERE / "capabilities.yaml").read_text(encoding="utf-8"))["capabilities"]}
untagged = yaml.safe_load((HERE / "untagged.yaml").read_text(encoding="utf-8"))["untagged"]
errors, where = [], {}
for md in sorted(ARCH.rglob("*.md")):
    rel = md.relative_to(ARCH).as_posix()
    if rel.startswith(("baseline/", "changes/")) or rel == "TRACEABILITY.md":
        continue
    heading = None
    for n, line in enumerate(md.read_text(encoding="utf-8").split("\n"), 1):
        if line.startswith("#"):
            heading = line.lstrip("#").strip()
        if line.startswith("> Capabilities:"):
            m = TAG.match(line)
            ids = [x.strip() for x in m.group(1).split("·")[0].split(",")] if m else []
            if not m or not ids or any(not CAP.match(i) for i in ids):
                errors.append(f"{rel}:{n}: malformed traceability line")
                continue
            for i in ids:
                if i not in caps:
                    errors.append(f"{rel}:{n}: unknown capability {i}")
                where.setdefault(i, []).append((rel, heading))
for cid in caps:
    if cid not in where and cid not in untagged:
        errors.append(f"{cid}: tagged nowhere and not listed in untagged.yaml")
    if cid in where and cid in untagged:
        errors.append(f"{cid}: tagged but also listed in untagged.yaml")
for cid in untagged:
    if cid not in caps:
        errors.append(f"untagged.yaml: unknown capability {cid}")

out = ["# Capability Traceability Index", "",
       "Generated by `audit-work/register/check_traceability.py`. Do not edit by hand.", "",
       f"Tagged: {len(where)} · Untagged (accounted for): {len(untagged)} · Total: {len(caps)}", "",
       "## Tagged capabilities", "", "| Capability | Title | Specified in |", "|---|---|---|"]
for cid in sorted(where, key=key):
    locs = "<br>".join(f"`{f}` · {h}" for f, h in where[cid])
    out.append(f"| {cid} | {caps[cid]['title']} | {locs} |")
out += ["", "## Untagged capabilities", "", "| Capability | Title | Status | Reference |", "|---|---|---|---|"]
for cid in sorted(untagged, key=key):
    u = untagged[cid]
    out.append(f"| {cid} | {caps[cid]['title']} | {u['status']} | {u['ref']} |")
(ARCH / "TRACEABILITY.md").write_text("\n".join(out) + "\n", encoding="utf-8")

if errors:
    print("FAIL"); [print(" ", e) for e in errors]; sys.exit(1)
print(f"PASS: {len(where)} tagged, {len(untagged)} untagged and accounted for, {len(caps)} total. Wrote architecture/TRACEABILITY.md")
